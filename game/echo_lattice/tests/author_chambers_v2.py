def R(*rows: str) -> list[str]:
    """Pad/truncate each row to GRID_W. Short rows (PR #48 style) open the
    right edge as floor — same loader behavior as chamber.gd."""
    out = []
    for r in rows:
        if len(r) > GRID_W:
            raise ValueError(f"row len {len(r)} > {GRID_W}: {r!r}")
        if len(r) < GRID_W:
            r = r + (" " * (GRID_W - len(r)))
        out.append(r)
    if len(out) != GRID_H:
        raise ValueError(f"map height {len(out)} != {GRID_H}")
    return out


