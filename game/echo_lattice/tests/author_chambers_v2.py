def find_glyph(rows: list[str], glyph: str) -> list[tuple[int, int]]:
    hits = []
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == glyph:
                hits.append((x, y))
    return hits


def is_walkable_char(ch: str) -> bool:
    return ch in {".", "P", "G", "C", " "}


def bfs_reachable(rows: list[str], start: tuple[int, int], goal: tuple[int, int],
                  blocked: set[tuple[int, int]] | None = None) -> bool:
    blocked = blocked or set()
    q = deque([start])
    seen = {start}
    while q:
        x, y = q.popleft()
        if (x, y) == goal:
            return True
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nx, ny = x + dx, y + dy
            if not (0 <= nx < GRID_W and 0 <= ny < GRID_H):
                continue
            if (nx, ny) in seen or (nx, ny) in blocked:
                continue
            if rows[ny][nx] == "#":
                continue
            seen.add((nx, ny))
            q.append((nx, ny))
    return False


def apply_transform(name: str, path: list[tuple[int, int]]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    if name == "none":
        return out
    if name == "mirror_v":
        for x, y in path:
            out.append((GRID_W - 1 - x, y))
    elif name == "mirror_h":
        for x, y in path:
            out.append((x, GRID_H - 1 - y))
    elif name == "rotate_180":
        for x, y in path:
            out.append((GRID_W - 1 - x, GRID_H - 1 - y))
    elif name == "thicken":
        out.extend(path)
    elif name == "mirror_v_then_h":
        for x, y in path:
            out.append((GRID_W - 1 - x, y))
            out.append((x, GRID_H - 1 - y))
    return out


class Sim:
    """Minimal rewrite simulator matching chamber.gd safety-net semantics."""

    WALL, FLOOR, CP, CP_USED, GOAL, ECHO = range(6)

    def __init__(self, rows: list[str], transform: str):
        self.transform = transform
        self.grid = [[self.FLOOR for _ in range(GRID_W)] for _ in range(GRID_H)]
        self.player = (0, 0)
        self.goal = (0, 0)
        self.path: list[tuple[int, int]] = []
        self.triggered: set[tuple[int, int]] = set()
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch == "#":
                    self.grid[y][x] = self.WALL
                elif ch == "P":
                    self.player = (x, y)
                elif ch == "G":
                    self.grid[y][x] = self.GOAL
                    self.goal = (x, y)
                elif ch == "C":
                    self.grid[y][x] = self.CP

    def blocked(self, p: tuple[int, int], extra: set[tuple[int, int]] | None = None) -> bool:
        x, y = p
        if not (0 <= x < GRID_W and 0 <= y < GRID_H):
            return True
        if extra and p in extra:
            return True
        return self.grid[y][x] in (self.WALL, self.ECHO)

    def reachable(self, extra: set[tuple[int, int]] | None = None) -> bool:
        q = deque([self.player])
        seen = {self.player}
        while q:
            cur = q.popleft()
            if cur == self.goal:
                return True
            x, y = cur
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                n = (x + dx, y + dy)
                if n in seen or self.blocked(n, extra):
                    continue
                seen.add(n)
                q.append(n)
        return False

    def step(self, d: tuple[int, int]) -> bool:
        nx, ny = self.player[0] + d[0], self.player[1] + d[1]
        if self.blocked((nx, ny)):
            return False
        self.player = (nx, ny)
        self.path.append(self.player)
        cell = self.grid[ny][nx]
        if cell == self.CP and self.player not in self.triggered:
            self.triggered.add(self.player)
            self.grid[ny][nx] = self.CP_USED
            self._rewrite()
        return True

    def _rewrite(self) -> None:
        path = list(self.path) if self.path else [self.player]
        transformed = apply_transform(self.transform, path)
        pending: list[tuple[int, int]] = []
        seen: set[tuple[int, int]] = set()
        for p in transformed:
            if p in seen or p == self.player or p == self.goal:
                continue
            x, y = p
            if not (0 <= x < GRID_W and 0 <= y < GRID_H):
                continue
            if self.grid[y][x] != self.FLOOR:
                continue
            seen.add(p)
            extra = set(pending) | {p}
            if self.reachable(extra):
                pending.append(p)
        for x, y in pending:
            self.grid[y][x] = self.ECHO
        self.path.clear()

    def bfs_next(self, target: tuple[int, int]) -> tuple[int, int] | None:
        if self.player == target:
            return None
        came = {self.player: self.player}
        q = deque([self.player])
        found = False
        while q:
            cur = q.popleft()
            if cur == target:
                found = True
                break
            x, y = cur
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                n = (x + dx, y + dy)
                if n in came or self.blocked(n):
                    continue
                came[n] = cur
                q.append(n)
        if not found:
            return None
        cur = target
        while came[cur] != self.player:
            cur = came[cur]
        return (cur[0] - self.player[0], cur[1] - self.player[1])

    def nearest_checkpoint(self) -> tuple[int, int] | None:
        best = None
        best_d = 10**9
        for y in range(GRID_H):
            for x in range(GRID_W):
                if self.grid[y][x] == self.CP:
                    d = abs(x - self.player[0]) + abs(y - self.player[1])
                    if d < best_d:
                        best_d = d
                        best = (x, y)
        return best

    def playthrough(self, max_moves: int = 500) -> bool:
        for _ in range(max_moves):
            if self.player == self.goal:
                return True
            target = self.nearest_checkpoint() or self.goal
            step = self.bfs_next(target)
            if step is None:
                step = self.bfs_next(self.goal)
                if step is None:
                    return self.player == self.goal
            if not self.step(step):
                return False
        return self.player == self.goal


def variations_for(ch: dict) -> dict:
    transform = ch["transform"]
    role = ch.get("role", "lesson")
    # Lesson chambers that depend on axis keep reflect gated.
    allow_reflect = transform in {"none", "rotate_180", "thicken"} or role in {"hard", "daily_showcase"}
    allow_rotate = transform in {"none", "thicken"} and role != "boss"
    return {
        "allow_rotate": allow_rotate,
        "allow_reflect": allow_reflect,
        "allow_palette_swap": True,
        "budget_deltas": [0, 1] if role == "hard" else [0],
        "hard_mode": {
            "tempo_delta": -8 if ch["difficulty"] >= 3 else -4,
            "par_moves_mult": 0.85,
        },
    }


def build_record(raw: dict, index: int) -> dict:
    act = raw["act"]
    act_meta = next(a for a in ACTS if a["id"] == act)
    slug = raw["slug"]
    cid = f"{index:02d}_{slug}"
    rows = raw["map"]
    ps = find_glyph(rows, "P")
    gs = find_glyph(rows, "G")
    cs = find_glyph(rows, "C")
    if len(ps) != 1 or len(gs) != 1:
        raise ValueError(f"{slug}: need exactly one P and one G")
    motifs = []
    for i, (x, y) in enumerate(cs):
        motifs.append({
            "id": f"M{i+1}",
            "kind": "CHECKPOINT",
            "cell": [x, y],
            "unique": True,
            "operator": raw["transform"] if raw["transform"] != "none" else None,
            "banner": raw["caption"] if i == 0 else "",
        })
    rec = {
        "id": cid,
        "index": index,
        "slug": slug,
        "title": raw["title"],
        "caption": raw["caption"],
        "act": act,
        "act_index": act_meta["index"],
        "act_title": act_meta["title"],
        "teaches": raw["teaches"],
        "transform": raw["transform"],
        "difficulty": raw["difficulty"],
        "role": raw.get("role", "lesson"),
        "identity": raw.get("identity"),
        "seed": raw["seed"],
        "daily_eligible": bool(raw.get(
            "daily_eligible",
            raw.get("role") in {"hard", "daily_showcase", "boss", "remix"}
            or raw.get("difficulty", 0) >= 2
        )),
        "hard_variant_of": raw.get("hard_variant_of"),
        "par_moves": raw["par_moves"],
        "tempo_start": 9999,
        "lattice": {
            "rows": GRID_H,
            "cols": GRID_W,
            "cells": rows,
        },
        "map": rows,  # playable loader convenience (PR #48 field)
        "motifs": motifs,
        "resonance": {"kind": "REACH_GOAL"},
        # Act defaults match Content Bible (1/2/3/3). Multi-checkpoint rooms
        # raise cap so every authored C can fire a rewrite (see 05 / 08).
        "rewrite": {
            "cap": max(
                1 if act_meta["index"] == 0 else (2 if act_meta["index"] == 1 else 3),
                len(cs),
            ),
            "forced_op": raw["transform"],
            "soft_hard_bias": 0.25 + 0.2 * act_meta["index"],
            "require_shorter_or_equal": False,
        },
        "hints": raw.get("hints", []),
        "variations": variations_for(raw),
        "unlocks": [],
        "tags": [act, raw["teaches"], raw["transform"], raw.get("role", "lesson")],
    }
    return rec


def validate_record(rec: dict) -> list[str]:
    errs: list[str] = []
    rows = rec["map"]
    if rec["transform"] not in TRANSFORMS:
        errs.append(f"{rec['id']}: bad transform {rec['transform']}")
    if len(rows) != GRID_H or any(len(r) != GRID_W for r in rows):
        errs.append(f"{rec['id']}: bad dimensions")
    ps = find_glyph(rows, "P")
    gs = find_glyph(rows, "G")
    if len(ps) != 1:
        errs.append(f"{rec['id']}: P count {len(ps)}")
    if len(gs) != 1:
        errs.append(f"{rec['id']}: G count {len(gs)}")
    if not ps or not gs:
        return errs
    if not bfs_reachable(rows, ps[0], gs[0]):
        errs.append(f"{rec['id']}: base layout not solvable P→G")
    for cx, cy in find_glyph(rows, "C"):
        if not bfs_reachable(rows, ps[0], (cx, cy)):
            errs.append(f"{rec['id']}: checkpoint {(cx, cy)} unreachable from P")
    # Playthrough with rewrite engine
    sim = Sim(rows, rec["transform"])
    if not sim.playthrough():
        errs.append(f"{rec['id']}: auto-solver playthrough failed")
    if rec["transform"] != "none" and not find_glyph(rows, "C"):
        errs.append(f"{rec['id']}: non-none transform needs a checkpoint")
    return errs


def write_daily_seeds(records: list[dict]) -> None:
    eligible = [r for r in records if r.get("daily_eligible")]
    # Fixed catalog of seeds for daily mode — date hashed into this list at runtime.
    seeds = []
    recipes = [
        {"rotate": 0, "reflect": "none", "palette": "default", "hard": False},
        {"rotate": 0, "reflect": "horizontal", "palette": "cool", "hard": False},
        {"rotate": 0, "reflect": "vertical", "palette": "warm", "hard": False},
        {"rotate": 180, "reflect": "none", "palette": "mono", "hard": False},
        {"rotate": 0, "reflect": "none", "palette": "default", "hard": True},
    ]
    for i, r in enumerate(eligible):
        recipe = recipes[i % len(recipes)]
        # Respect per-chamber gates
        if not r["variations"]["allow_reflect"]:
            recipe = {**recipe, "reflect": "none"}
        if not r["variations"]["allow_rotate"]:
            recipe = {**recipe, "rotate": 0}
        seeds.append({
            "seed": r["seed"],
            "chamber_id": r["id"],
            "slug": r["slug"],
            "label": f"daily/{r['slug']}",
            "variation": recipe,
            "friend_code": f"EL-{r['seed']:05d}",
        })
    payload = {
        "format": 2,
        "game": "echo_lattice",
        "note": "Daily mode picks seed = hash(YYYY-MM-DD) % len(seeds). Same day → same chamber+variation.",
        "hash": "fnv1a32(date_string) % len(seeds)",
        "seeds": seeds,
    }
    path = CONTENT / "daily" / "seeds.json"
    path.write_text(json.dumps(payload, indent=2) + "\n")
    print(f"wrote {path} ({len(seeds)} daily-ready seeds)")


def write_acts_index(records: list[dict]) -> None:
    acts = []
    for a in ACTS:
        members = [r["id"] for r in records if r["act"] == a["id"] and r["role"] != "hard"]
        hard = [r["id"] for r in records if r["act"] == a["id"] and r["role"] == "hard"]
        bosses = [r["id"] for r in records if r["act"] == a["id"] and r["role"] == "boss"]
        acts.append({
            **a,
            "chambers": members,
            "hard_variants": hard,
            "bosses": bosses,
        })
    payload = {
        "format": 2,
        "game": "echo_lattice",
        "grid": {"w": GRID_W, "h": GRID_H},
        "campaign_order": [r["id"] for r in records if r["role"] != "hard"],
        "hard_order": [r["id"] for r in records if r["role"] == "hard"],
        "acts": acts,
    }
    path = CONTENT / "acts.json"
    path.write_text(json.dumps(payload, indent=2) + "\n")
    print(f"wrote {path}")


def main() -> int:
    CHAMBERS_DIR.mkdir(parents=True, exist_ok=True)
    # Clear old chamber json
    for p in CHAMBERS_DIR.glob("*.json"):
        p.unlink()

    apply_map_overrides()
    raws = CHAMBERS + HARD_VARIANTS
    records: list[dict] = []
    errors: list[str] = []
    for i, raw in enumerate(raws):
        rec = build_record(raw, i)
        records.append(rec)
        errors.extend(validate_record(rec))

    if errors:
        print("VALIDATION FAILED:")
        for e in errors:
            print(" ", e)
        return 1

    for rec in records:
        path = CHAMBERS_DIR / f"{rec['id']}.json"
        # Drop None identity for cleaner files
        out = {k: v for k, v in rec.items() if v is not None}
        path.write_text(json.dumps(out, indent=2) + "\n")

    write_acts_index(records)
    write_daily_seeds(records)

    # Summary
    by_act: dict[str, int] = {}
    roles: dict[str, int] = {}
    for r in records:
        by_act[r["act"]] = by_act.get(r["act"], 0) + 1
        roles[r["role"]] = roles.get(r["role"], 0) + 1
    print(f"authored {len(records)} chambers")
    print(f"  by act: {by_act}")
    print(f"  by role: {roles}")
    print("all playthroughs OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
